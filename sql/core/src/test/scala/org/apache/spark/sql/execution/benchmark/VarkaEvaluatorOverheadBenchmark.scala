package org.apache.spark.sql.execution.benchmark

import java.nio.charset.StandardCharsets

import org.apache.arrow.memory.BufferAllocator
import org.apache.arrow.vector.{BaseFixedWidthVector, BigIntVector, DateDayVector, VarCharVector}

import org.apache.spark.{PartitionEvaluator, TaskContext}
import org.apache.spark.benchmark.Benchmark
import org.apache.spark.sql.catalyst.expressions.{Alias, Attribute, AttributeReference, DateAdd,
  Expression, GreaterThan, Least, Literal, TruncDate}
import org.apache.spark.sql.execution.{VarkaExecMetrics, VarkaFilterEvaluatorFactory,
  VarkaProjectEvaluatorFactory}
import org.apache.spark.sql.execution.metric.SQLMetrics
import org.apache.spark.sql.types.{DateType, LongType, StringType}
import org.apache.spark.sql.util.ArrowUtils
import org.apache.spark.sql.vectorized.{ArrowColumnVector, ColumnarBatch}

/**
 * What a Varka evaluator costs per batch, apart from what its kernel costs per row (VARKA-251).
 *
 * Every Varka node hands each input batch to an evaluator, which checks the batch can take the
 * kernel, fills the kernel's argument arrays, allocates the output vectors, runs the kernel, and
 * tracks the output batch for release. That work is per batch, so it shows where batches are
 * small. VARKA-251 splits `VarkaEvaluatorBase`, which does all of it, into Java components, and
 * this file is the proof that the split costs nothing per batch: committed first against the
 * unchanged code, then regenerated by the split.
 *
 * The evaluators are driven directly, as `VarkaProjectExecSuite` drives them, over Arrow batches
 * built once and read by every iteration, inside a task context of their own; no Spark job runs.
 * Each `Benchmark` counts its batches as its values, so the "Per Row(ns)" column is nanoseconds
 * per batch. Four shapes, one per path through the per-batch machinery:
 *
 *   int lane       `date_add(d, 3)`, a projection
 *   long lane      `least(l, 5000000000)`, a projection over a `bigint`, the long literal table
 *   filter         `d > DATE'2000-01-01'`, the selection bitmap instead of output vectors
 *   derived input  `trunc(d, fmt)`, the format parsed into the evaluator's scratch per batch
 *
 * at 1, 16 and 1024 rows a batch. Every case checks afterwards that each of its batches went
 * through the kernel, so a shape that stopped fusing fails the run instead of timing the row
 * path.
 *
 * To run this benchmark:
 * {{{
 *   SPARK_GENERATE_BENCHMARK_FILES=1 build/sbt "sql/Test/runMain
 *     org.apache.spark.sql.execution.benchmark.VarkaEvaluatorOverheadBenchmark"
 * }}}
 */
object VarkaEvaluatorOverheadBenchmark extends SqlBasedBenchmark {

  private val d = AttributeReference("d", DateType)()
  private val l = AttributeReference("l", LongType)()
  private val fmt = AttributeReference("fmt", StringType)()
  private val formats = Seq("YEAR", "MONTH", "QUARTER", "WEEK")

  /** One shape: its input columns, and a fresh evaluator over them with its metrics. */
  private case class Shape(
      name: String,
      input: Seq[Attribute],
      evaluator: VarkaExecMetrics => PartitionEvaluator[ColumnarBatch, ColumnarBatch])

  private def project(expression: Expression, input: Seq[Attribute]): Shape = Shape(
    s"${expression.sql}", input, metrics => new VarkaProjectEvaluatorFactory(
      Seq(Alias(expression, "out")()), input, offHeapColumnVectorEnabled = false,
      classDumpDirectory = None, SQLMetrics.createMetric(spark.sparkContext, "rows"),
      SQLMetrics.createMetric(spark.sparkContext, "batches"), metrics).createEvaluator())

  private def filter(condition: Expression, input: Seq[Attribute]): Shape = Shape(
    s"filter ${condition.sql}", input, metrics => new VarkaFilterEvaluatorFactory(
      condition, input, offHeapColumnVectorEnabled = false, classDumpDirectory = None,
      SQLMetrics.createMetric(spark.sparkContext, "rows"),
      SQLMetrics.createMetric(spark.sparkContext, "batches"), metrics).createEvaluator())

  private lazy val shapes = Seq(
    project(DateAdd(d, Literal(3)), Seq(d)),
    project(Least(Seq(l, Literal(5000000000L))), Seq(l)),
    filter(GreaterThan(d, Literal.create(java.sql.Date.valueOf("2000-01-01"), DateType)), Seq(d)),
    project(TruncDate(d, fmt), Seq(d, fmt)))

  /** A batch of `rows` rows of `input`'s columns, every tenth value null. */
  private def batch(input: Seq[Attribute], rows: Int, seed: Int,
      allocator: BufferAllocator): ColumnarBatch = {
    val columns = input.map { a =>
      val vector = ArrowUtils.toArrowField(a.name, a.dataType, nullable = true, null)
        .createVector(allocator)
      vector match {
        case v: VarCharVector => v.allocateNew(rows * 8L, rows)
        case v: BaseFixedWidthVector => v.allocateNew(rows)
      }
      var i = 0
      while (i < rows) {
        val k = seed * rows + i
        (vector, k % 10 == 9) match {
          case (v: DateDayVector, true) => v.setNull(i)
          case (v: DateDayVector, false) => v.setSafe(i, 10000 + k % 20000)
          case (v: BigIntVector, true) => v.setNull(i)
          case (v: BigIntVector, false) => v.setSafe(i, k * 7L)
          // The format is never null: a null format is a null answer the kernel never sees.
          case (v: VarCharVector, _) =>
            v.setSafe(i, formats(k % formats.size).getBytes(StandardCharsets.UTF_8))
          case (v, _) => throw new IllegalArgumentException(s"no values for a ${v.getClass}")
        }
        i += 1
      }
      vector.setValueCount(rows)
      new ArrowColumnVector(vector)
    }
    new ColumnarBatch(columns.toArray, rows)
  }

  /**
   * One task's worth: a fresh evaluator over `inputs`, every output batch taken, which releases
   * the one before it, then the task completed. The kernel class comes from the shape cache after
   * the first task, as it does for every task of a query.
   */
  private def runTask(shape: Shape, inputs: Seq[ColumnarBatch], metrics: VarkaExecMetrics)
      : Long = {
    val context = TaskContext.empty()
    TaskContext.setTaskContext(context)
    try {
      val out = shape.evaluator(metrics).eval(0, inputs.iterator)
      var rows = 0L
      while (out.hasNext) {
        rows += out.next().numRows()
      }
      context.markTaskCompleted(None)
      rows
    } finally {
      TaskContext.unset()
    }
  }

  override def runBenchmarkSuite(mainArgs: Array[String]): Unit = {
    val allocator = ArrowUtils.rootAllocator.newChildAllocator("varka-overhead", 0,
      Long.MaxValue)
    try {
      for ((rows, batches) <- Seq((1, 20000), (16, 20000), (1024, 2000))) {
        runBenchmark(s"Varka evaluator per batch, $rows rows a batch") {
          val benchmark = new Benchmark(s"$rows rows a batch, ns per batch", batches,
            output = output)
          val cases = shapes.map { shape =>
            val inputs = (0 until batches).map(batch(shape.input, rows, _, allocator))
            val metrics = VarkaExecMetrics(
              varkaBatches = Some(SQLMetrics.createMetric(spark.sparkContext, "varka")))
            benchmark.addCase(shape.name) { _ => runTask(shape, inputs, metrics) }
            (shape, inputs, metrics)
          }
          try {
            benchmark.run()
            cases.foreach { case (shape, _, metrics) =>
              val served = metrics.varkaBatches.get.value
              // Every iteration served every batch by the kernel, the warm-up iterations too.
              assert(served > 0 && served % batches == 0, s"${shape.name}: $served of its " +
                s"batches took the kernel, not a multiple of $batches")
            }
          } finally {
            cases.foreach(_._2.foreach(_.close()))
          }
        }
      }
    } finally {
      allocator.close()
    }
  }
}
